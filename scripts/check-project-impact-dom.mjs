// Supplemental interaction checks; browser layout/focus/touch still require Playwright.
const { Window } = await import(process.env.HBL_DOM_MODULE || 'happy-dom');
import { readFileSync } from 'node:fs';
import { strict as assert } from 'node:assert';
const root = new URL('..', import.meta.url);
const window = new Window({ url: 'http://localhost/world/invention/impact/' });
window.document.write(readFileSync(new URL('world/invention/impact/index.html', root), 'utf8').replace(/<script[\s\S]*?<\/script>/g, ''));
globalThis.window = window;
globalThis.document = window.document;
let callback = null, cancelled = 0;
globalThis.requestAnimationFrame = fn => { callback = fn; return 1; };
globalThis.cancelAnimationFrame = () => { callback = null; cancelled++; };
await import(new URL('world/invention/impact/page.js', root));
const $ = id => document.getElementById(id);
const change = (id, value, event = 'change') => { $(id).value = value; $(id).dispatchEvent(new window.Event(event)); };
assert.match($('estimate').textContent, /80,000/);
change('capacity', '8', 'input'); callback(); callback = null;
assert.match($('estimate').textContent, /160,000/);
assert.match($('manifest').textContent, /transit-d1-8/);
assert.match($('outcome').textContent, /No plan executed/);
$('undo').click(); assert.equal($('capacity').value, '4');
change('numeric', '100'); assert.equal($('capacity').value, '12');
$('run').click(); assert.match($('outcome').textContent, /Current executed plan: \+12/);
const link = $('replay').href;
change('numeric', '4'); assert.match($('outcome').textContent, /Previous executed plan: \+12/);
assert.equal($('replay').href, link);
change('numeric', ''); assert.match($('error').textContent, /finite/);
assert.equal($('capacity').value, '4');
change('project', 'housing'); assert.equal($('controls').hidden, true); assert.equal($('unsupported').hidden, false);
change('project', 'upzone'); assert.equal($('controls').hidden, true);
change('project', 'transit'); assert.equal($('controls').hidden, false);
change('capacity', '8', 'input');
window.dispatchEvent(new window.Event('pagehide'));
assert.equal(cancelled, 1); assert.equal(callback, null);
const oldManifest = $('manifest').textContent;
change('numeric', '12'); assert.equal($('manifest').textContent, oldManifest);
console.log('PASS: actual impact page DOM: catalog mapping, undo, clamping, execution, stale labels, invalid/unsupported states, replay identity, pending-frame and listener cleanup (18 assertions).');
await window.happyDOM.abort();
