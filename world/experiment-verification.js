import { validateCivicExperiment } from "./experiment-contract.js";
import { generateWorlds } from "./world-generator.js";
import { createImplementationStressAdapter, simulateExperiment } from "./simulation-adapter.js";
import { summarizeOutcomes } from "./outcome-analysis.js";

function sameJson(a, b) {
  return JSON.stringify(a) === JSON.stringify(b);
}

function pass(id, detail, data = undefined) {
  return { id, ok: true, detail, data };
}

function fail(id, detail, data = undefined) {
  return { id, ok: false, detail, data };
}

function firstVariable(experiment) {
  return experiment?.worldModel?.variables?.find((variable) => variable && typeof variable.id === "string") || null;
}

export async function runExperimentVerification(experiment, options = {}) {
  const checks = [];
  const contract = validateCivicExperiment(experiment);
  checks.push(contract.ok
    ? pass("contract", `civic-experiment.v1 is structurally valid (${contract.variableCount} variables)`)
    : fail("contract", contract.errors.join("; "), contract.errors));

  if (!contract.ok) return { ok: false, checks };

  const runs = Math.max(4, Math.min(64, Number(options.runs) || 16));
  const seed = Number.isFinite(Number(experiment?.experiment?.seed)) ? Number(experiment.experiment.seed) : 424242;
  const a = generateWorlds(experiment, { runs, seed });
  const b = generateWorlds(experiment, { runs, seed });
  checks.push(sameJson(a.worlds, b.worlds)
    ? pass("determinism", `same seed ${seed} generated byte-equivalent world vectors`)
    : fail("determinism", `same seed ${seed} generated different worlds`));

  const sampleVariable = firstVariable(experiment);
  if (sampleVariable) {
    const baseline = Number(sampleVariable.baseline);
    const lockedValue = Number.isFinite(baseline) ? baseline : 0.5;
    const locked = generateWorlds(experiment, {
      runs,
      seed,
      overrides: {
        [sampleVariable.id]: {
          baseline: lockedValue,
          min: lockedValue,
          max: lockedValue,
          locked: true,
          reason: "verification lock",
        },
      },
    });
    const lockedOk = locked.worlds.every((world) => world.conditions?.[sampleVariable.id] === lockedValue);
    checks.push(lockedOk
      ? pass("locked-variable", `${sampleVariable.id} stayed fixed at ${lockedValue} across ${runs} worlds`)
      : fail("locked-variable", `${sampleVariable.id} changed despite being locked`));
  }

  const changedSeed = generateWorlds(experiment, { runs, seed: (seed + 1) >>> 0 });
  const hasSampledVariable = experiment.worldModel.variables.some((variable) => !variable.locked && Number(variable?.range?.max) > Number(variable?.range?.min));
  if (hasSampledVariable) {
    checks.push(!sameJson(a.worlds, changedSeed.worlds)
      ? pass("seed-sensitivity", "changing the seed changed sampled worlds")
      : fail("seed-sensitivity", "changing the seed did not change sampled worlds"));
  } else {
    checks.push(pass("seed-sensitivity", "all variables are fixed; seed sensitivity is not applicable"));
  }

  const adapter = createImplementationStressAdapter();
  const batch = await simulateExperiment(experiment, a, adapter, { concurrency: 8 });
  const finite = batch.simulations.length === runs
    && batch.simulations.every((simulation) => Number.isFinite(simulation.score)
      && Object.values(simulation.metrics || {}).every((value) => typeof value !== "number" || Number.isFinite(value)));
  checks.push(finite
    ? pass("simulation-finite", `${batch.simulations.length}/${runs} simulations returned finite results`)
    : fail("simulation-finite", "simulation output contains missing, NaN, or infinite values"));

  const summary = summarizeOutcomes(batch);
  const summaryOk = Number.isFinite(summary.expectedScore)
    && Number.isFinite(summary.robustness)
    && Array.isArray(summary.tailRisks);
  checks.push(summaryOk
    ? pass("outcome-summary", `expected score ${summary.expectedScore}; robustness ${(summary.robustness * 100).toFixed(1)}%`)
    : fail("outcome-summary", "outcome summary is incomplete or non-finite", summary));

  return {
    ok: checks.every((check) => check.ok),
    checks,
    testedAt: new Date().toISOString(),
    seed,
    runs,
  };
}

export function formatVerificationReport(report) {
  return report.checks
    .map((check) => `${check.ok ? "PASS" : "FAIL"}  ${check.id.padEnd(18)} ${check.detail}`)
    .join("\n");
}
