import {test,expect} from '@playwright/test';

test('500 real futures: ghost comparison, criteria, bounded search, density, lasso and exact monthly entry',async({page})=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/world/decision/visualization.css');
  await page.setContent('<div id="visual-test" style="max-width:1100px;margin:auto"></div>');
  const elapsed=await page.evaluate(async()=>{
    const {mountDecisionVisualizations,futureOutcome}=await import('/world/decision/visualizations.js');
    const {DECISION_ENGINE_VERSION}=await import('/world/decision/contracts.js');
    const {housingModel,createHousingScenarios,simulateHousingRun}=await import('/world/models/housing/index.js');
    const scenarios=createHousingScenarios().map(s=>({...s,successCriterion:{metricId:'affordability',operator:'gte',value:70}})),runs=[],prior=[];
    for(let i=0;i<500;i++){
      const scenario=scenarios[i%4],seed=Math.floor(i/4),identity={id:`run-${i}`,experimentId:'visual-test',scenarioId:scenario.id,seed,status:'completed',engineVersion:DECISION_ENGINE_VERSION,modelVersion:housingModel.version};
      runs.push({...identity,...simulateHousingRun({parameters:scenario.parameters,seed,years:2})});
      prior.push({...identity,id:`prior-${i}`,...simulateHousingRun({parameters:scenario.id==='plan-a'?{...scenario.parameters,construction_capacity:scenario.parameters.construction_capacity*.8}:scenario.parameters,seed,years:2})});
    }
    window.visualFailures=runs.filter(r=>futureOutcome(r,scenarios.find(s=>s.id===r.scenarioId))==='failure').length;
    const start=performance.now();window.visualView=mountDecisionVisualizations(document.querySelector('#visual-test'),{onSelectRun:r=>window.visualSelection=r,onEnterFuture:(r,context)=>window.visualEntry={run:r.id,...context}});
    window.visualResults={experiment:{id:'visual-test',scenarios,years:2,status:'completed',modelId:housingModel.id,modelVersion:housingModel.version},runs,model:housingModel,previousResults:{experiment:{id:'prior-test',modelId:housingModel.id,modelVersion:housingModel.version,years:2},runs:prior},aggregates:[],comparisons:[]};visualView.update(visualResults);
    return performance.now()-start;
  });
  expect(elapsed).toBeLessThan(2000);
  await page.locator('[data-control=color]').selectOption('outcome');
  await page.locator('[data-control=outcome]').selectOption('failure');
  await expect(page.locator('[data-filter-note]')).toContainText(`${await page.evaluate(()=>visualFailures)} matching futures`);
  await page.locator('[data-control=outcome]').selectOption('');
  await page.locator('[data-control=search]').fill('rent below 999999 and cost >= 0');
  await expect(page.locator('[data-filter-note]')).toContainText('500 matching futures');
  await page.locator('[data-control=search]').fill('unknown > 10');
  await expect(page.locator('[data-search-note]')).toContainText('Unknown');
  await page.locator('[data-control=search]').fill('');
  await expect(page.locator('[data-ghost-run]')).toHaveCount(500);
  await page.locator('[data-control=density]').check();
  await expect(page.locator('[data-density-support]')).toHaveCount(3);
  await expect(page.locator('[data-paired-strip]')).toContainText('500 matched pairs');
  await expect(page.locator('[data-paired-scenario]')).toHaveCount(8);
  await page.evaluate(()=>visualView.update({...visualResults,previousResults:{...visualResults.previousResults,experiment:{...visualResults.previousResults.experiment,modelVersion:'incompatible'}}}));
  await expect(page.locator('[data-paired-strip]')).toContainText('Paired changes are withheld');
  await expect(page.locator('[data-paired-scenario]')).toHaveCount(0);
  await page.evaluate(()=>visualView.update(visualResults));
  await page.locator('[data-viz=worlds]').evaluate(grid=>grid.closest('details').open=true);
  await page.locator('[data-control=grid-size]').selectOption('500');
  await expect(page.locator('[data-viz=worlds] button')).toHaveCount(500);
  await page.locator('[data-control=lasso]').click();
  await page.locator('[data-viz=landscape]').scrollIntoViewIfNeeded();
  const box=await page.locator('[data-viz=landscape]').boundingBox();
  await page.mouse.move(box.x+.08*box.width,box.y+.01*box.height);await page.mouse.down();
  for(const [x,y] of [[.99,.01],[.99,.92],[.08,.92],[.08,.01]])await page.mouse.move(box.x+x*box.width,box.y+y*box.height,{steps:5});
  await page.mouse.up();
  await expect(page.locator('[data-lasso-support]')).toContainText('500 selected');
  await page.locator('[data-control=lasso]').click();
  await page.locator('[data-control=median]').click();
  await page.locator('[data-control=replay-year]').fill('7');
  await expect(page.locator('[data-control=replay-year]')).toHaveAttribute('aria-valuetext',/Month 7/);
  await page.locator('[data-control=enter]').click();
  expect(await page.evaluate(()=>visualEntry.run===visualSelection.id&&visualEntry.month===7)).toBe(true);
  expect(await page.locator('[data-event-year]').count()).toBeGreaterThan(0);
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.evaluate(()=>visualView.destroy());
  expect(errors).toEqual([]);
});

test('entering a stored future restores its exact scenario, run and month in the physical world',async({page,request})=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.route('**/api/outcomes',route=>route.fulfill({json:{outcomes:[]}}));
  await page.route('**/api/overpass-health',route=>route.fulfill({json:{ok:true}}));
  await page.goto('/world/decision/visualization.css');
  const input=await page.evaluate(async()=>{
    const {housingModel,createHousingScenarios}=await import('/world/models/housing/index.js');
    const {createBuildingProposal}=await import('/world/buildings/proposal.js');
    const scenarios=createHousingScenarios().slice(0,2);
    scenarios[1].projects=[createBuildingProposal({id:'future-entry-project',location:{x:0,z:140},status:'approved',construction:{permitMonths:1,buildMonths:6}})];
    return {schemaVersion:'decision-experiment.v1',name:'Exact future visual test',decision:'Inspect one stored future',modelId:housingModel.id,modelVersion:housingModel.version,seed:42,runs:1,years:2,scenarios,metadata:{test:'visualization-entry'}};
  });
  const createdResponse=await request.post('/api/decision-experiments',{data:input});
  expect(createdResponse.ok()).toBe(true);
  const {experiment}=await createdResponse.json();
  await request.post(`/api/decision-experiments/${experiment.id}/start`,{data:{}});
  let result;
  await expect.poll(async()=>{result=await(await request.get(`/api/decision-experiments/${experiment.id}/results`)).json();return result.experiment.status},{timeout:30000}).toBe('completed');
  const run=result.runs.find(row=>row.scenarioId==='plan-a');
  expect(run.monthlyTimeline.length).toBeGreaterThan(12);
  await page.goto(`/world?demo=1&people=20&renderer=webgl&decisionExperiment=${experiment.id}&decisionRun=${run.id}&month=7`);
  const root=page.locator('[data-testid=world-building-tools]');
  await expect(root).toHaveAttribute('data-entered-future',run.id);
  await expect(root).toHaveAttribute('data-trace-state','loaded');
  await expect(root).toHaveAttribute('data-trace-loaded-run',run.id);
  await expect(page.locator('[data-bw-time]')).toHaveText('7');
  await expect(page.locator('[data-bw-run]')).toHaveValue(run.id);
  await expect(page.locator('[data-bw-scenario]')).toHaveValue('plan-a');
  await expect(page.locator('[data-bw-future-metrics]')).toContainText('Recorded month 7');
  await page.locator('[data-bw-month]').fill('11');
  const link=new URL(await page.locator('[data-bw-link]').getAttribute('href'),page.url());
  expect(link.searchParams.get('run')).toBe(run.id);expect(link.searchParams.get('month')).toBe('11');expect(link.hash).toBe('#futures');
  await page.locator('[data-bw-month]').fill('24');
  await expect(root.locator('.bw-selection')).not.toContainText('Phase: proposed');
  await expect(root.locator('.bw-selection')).toContainText('Floors: 24 / 24');
  expect(errors).toEqual([]);
});
