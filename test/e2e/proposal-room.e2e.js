import { test, expect } from '@playwright/test';
test('local tabs preserve concurrent drafts, review, keyboard and deletion', async ({page, context}) => {
  await page.setViewportSize({width:390,height:844});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('/world/invention/');
  await page.getByRole('link',{name:'Proposal room',exact:true}).click();
  await page.getByLabel('Display name').fill('Ada');
  await page.getByLabel('Opt in').check();
  await page.getByRole('button',{name:'Create or join'}).click();
  const identity = await page.locator('#identity').textContent();
  const id = identity.split(' · ')[0].replace('Room ','');
  const guest = await context.newPage();
  await guest.goto('/world/invention/room/');
  await guest.getByLabel('Display name').fill('Bo');
  await guest.getByLabel('Opt in').check();
  await guest.getByLabel('Local room ID').fill(id);
  await guest.getByRole('button',{name:'Create or join'}).click();
  await guest.getByLabel('Spatial policy').selectOption('transit-d0-8');
  await Promise.all([page.getByRole('button',{name:'Add proposal',exact:true}).click(),guest.getByRole('button',{name:'Add proposal',exact:true}).click()]);
  await expect(page.locator('#proposals label')).toHaveCount(2);
  await expect(guest.locator('#proposals')).toContainText('Ada');
  await expect(guest.locator('#review')).toBeDisabled();
  await page.reload();
  await expect(page.locator('#proposals label')).toHaveCount(2);
  for (const input of await page.locator('#proposals input').all()) await input.check();
  await page.locator('#review').click();
  await expect(page.locator('#status')).toContainText('one option');
  await page.locator('#proposals input').first().uncheck();
  await page.locator('#review').focus(); await page.keyboard.press('Enter');
  await expect(page.locator('#submit')).toBeEnabled();
  await guest.getByLabel('Comment', {exact:true}).fill('Check utility assumptions');
  await guest.getByRole('button',{name:'Add comment'}).click();
  await expect(page.locator('#submit')).toBeDisabled();
  await page.locator('#review').click();
  await page.screenshot({path:'.mini-symphony-evidence/SHE-770-room-mobile.png',fullPage:true});
  await page.locator('#submit').click();
  await expect(page).toHaveURL(/invention\/future\/\?plan=/);
  await page.goBack();
  await page.locator('#delete').click();
  await expect(guest.locator('#status')).toContainText('Access denied');
  await guest.reload();
  await expect(guest.locator('#canvas')).toBeHidden();
});
