import { test, expect } from '@playwright/test';
for (const width of [1440, 390]) test(`third-place navigation, cancel, missing source and replay at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/world/invention/');
  await page.getByRole('link', { name: 'Third Place Designer' }).click();
  await expect(page.getByRole('heading', { name: 'Third Place Designer', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Confirm design' }).focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('status')).toContainText('challenge passed');
  await expect(page.locator('#checkpoint')).toContainText('66000');
  const receipt = await page.locator('#receipt').inputValue();
  await page.getByLabel('Project', { exact: true }).selectOption('plaza');
  await expect(page.locator('#preview')).toContainText('90,000');
  await page.getByRole('button', { name: 'Cancel draft' }).click();
  expect(await page.locator('#receipt').inputValue()).toBe(receipt);
  await page.getByRole('button', { name: 'Before', exact: true }).click();
  await expect(page.locator('#lot')).toContainText('Empty lot');
  await page.getByRole('button', { name: 'After', exact: true }).click();
  await expect(page.locator('#lot')).toContainText('Pocket park');
  await page.getByRole('button', { name: 'Clear source data' }).click();
  await expect(page.getByRole('status')).toContainText('No source data');
  await expect(page.getByRole('button', { name: 'Confirm design' })).toBeDisabled();
  await page.getByRole('button', { name: 'Load pinned demo' }).click();
  const bad = JSON.parse(receipt); bad.after.seed++;
  await page.locator('#receipt').fill(JSON.stringify(bad));
  await page.getByRole('button', { name: 'Verify and replay' }).click();
  await expect(page.getByRole('status')).toContainText('Replay mismatch');
  await expect(page.locator('#lot')).toContainText('Pocket park');
  await page.reload();
  await page.locator('#receipt').fill(receipt);
  await page.getByRole('button', { name: 'Verify and replay' }).click();
  await expect(page.getByRole('status')).toContainText('Design replay verified');
  await expect(page.locator('#checkpoint')).toContainText('unavailable');
  await page.getByLabel('Project', { exact: true }).selectOption('plaza');
  await page.getByRole('button', { name: 'Confirm design' }).click();
  await expect(page.locator('#checkpoint')).toContainText('90000');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
