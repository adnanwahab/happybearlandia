import { test, expect } from '@playwright/test';
for (const width of [1440, 390]) test(`boundary preview at ${width}px: unsupported parcel, exact units, reject, cancel and apply`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/world/invention/');
  await page.getByRole('link', { name: 'Tabletop Block' }).click();
  await page.getByRole('button', { name: 'Enter tabletop mode' }).click();
  const open = page.getByRole('button', { name: 'Preview raised boundary and offsets' });
  await open.click();
  await expect(page.getByText('Parcel editing unsupported:', { exact: false })).toBeVisible();
  const x = page.getByLabel('Proposed X offset (meters)');
  await expect(x).toBeFocused();
  expect(await x.evaluate(el => getComputedStyle(el).outlineStyle)).not.toBe('none');
  await expect(page.locator('#boundary-reading')).toContainText('1532.90016 m²');
  await expect(page.locator('#boundary-shape polygon')).toHaveCount(5);
  await x.fill('100');
  await expect(page.locator('#boundary-reading')).toContainText('overlaps');
  await expect(page.getByRole('button', { name: 'Apply offsets to draft' })).toBeDisabled();
  await x.fill('');
  await expect(page.locator('#boundary-reading')).toContainText('finite meters');
  await expect(page.locator('#boundary-shape polygon')).toHaveCount(0);
  await x.fill('5');
  await expect(page.locator('#boundary-reading')).toContainText('Geometry checks pass');
  await expect(page.locator('#boundary-pacing')).toContainText('max frame wait');
  await page.getByRole('button', { name: 'Cancel boundary preview' }).click();
  await expect(open).toBeFocused();
  await expect(page.getByLabel('X (meters)', { exact: true })).toHaveValue('-50');
  await expect(page.locator('#boundary-shape polygon')).toHaveCount(0);
  await expect(page.locator('#boundary-pacing')).toHaveAttribute('data-pending', '0');
  await open.click(); await x.fill('5');
  await page.getByRole('button', { name: 'Apply offsets to draft' }).click();
  await expect(page.getByLabel('X (meters)', { exact: true })).toHaveValue('-45');
  await page.getByRole('button', { name: 'Exit and discard draft' }).click();
  await page.getByRole('button', { name: 'Enter tabletop mode' }).click();
  await expect(page.getByLabel('X (meters)', { exact: true })).toHaveValue('-50');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
