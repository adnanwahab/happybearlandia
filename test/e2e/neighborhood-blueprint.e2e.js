import { test, expect } from '@playwright/test';
import { createBlueprint, encodeBlueprint } from '../../world/invention/blueprint/model.js';
import { decodePlan } from '../../world/invention/model.js';
import { mkdirSync } from 'node:fs';

for (const mobile of [false, true]) test(`blueprint preview and explicit replacement ${mobile ? 'touch fallback' : 'keyboard'}`, async ({ page }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.setViewportSize(mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/world/invention/');
  await page.getByRole('link', { name: 'Neighborhood Blueprint' }).click();
  await expect(page.getByRole('heading', { name: 'Neighborhood Blueprint', exact: true })).toBeVisible();
  await page.locator('#parcel-d1-transit').selectOption('transit-d1-8');
  await page.locator('#parcel-d1-palette').selectOption('brick');
  await page.getByRole('button', { name: 'Update design' }).click();
  await page.getByRole('button', { name: 'Export JSON' }).click();
  const exported = JSON.parse(await page.getByLabel('Exported blueprint (copy or save as JSON)').inputValue());
  expect(exported.edits).toEqual([{ parcelId: 'parcel-d1', policyId: 'transit-d1-8' }]);
  expect(exported.cosmetics.find(row => row.parcelId === 'parcel-d1').palette).toBe('brick');
  const originalLink = await page.locator('#replay').getAttribute('href');
  const incoming = createBlueprint({ seed: 42, policies: ['housing-d0-3'] }, [{ parcelId: 'parcel-d0', palette: 'pastel' }]);
  await page.getByLabel('Blueprint JSON', { exact: true }).fill(encodeBlueprint(incoming));
  await page.getByRole('button', { name: 'Preview import' }).focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('status')).toContainText('nothing applied yet');
  expect(await page.locator('#replay').getAttribute('href')).toBe(originalLink);
  await expect(page.locator('#preview-result')).toContainText('Public housing units +3');
  await page.getByRole('button', { name: 'Confirm replacement' }).focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('status')).toContainText('Blueprint imported');
  const acceptedLink = await page.locator('#replay').getAttribute('href');
  expect(decodePlan(new URL(acceptedLink, 'http://localhost').searchParams.get('plan')).policies).toEqual(['housing-d0-3']);
  await page.getByRole('button', { name: 'Preview import' }).click();
  await expect(page.getByRole('status')).toContainText('Identical design');
  if (mobile) await page.getByRole('button', { name: 'Confirm replacement' }).tap();
  else await page.getByRole('button', { name: 'Confirm replacement' }).click();
  expect(await page.locator('#replay').getAttribute('href')).toBe(acceptedLink);
  const bad = structuredClone(incoming); bad.edits[0].parcelId = 'unsupported-parcel';
  await page.getByLabel('Blueprint JSON', { exact: true }).fill(JSON.stringify(bad));
  await page.getByRole('button', { name: 'Preview import' }).click();
  await expect(page.getByRole('status')).toContainText('Unsupported parcel');
  await expect(page.getByRole('button', { name: 'Confirm replacement' })).toBeDisabled();
  expect(await page.locator('#replay').getAttribute('href')).toBe(acceptedLink);
  bad.edits[0].parcelId = 'parcel-d0'; bad.modelVersion = 'next';
  await page.getByLabel('Blueprint JSON', { exact: true }).fill(JSON.stringify(bad));
  await page.getByRole('button', { name: 'Preview import' }).click();
  await expect(page.getByRole('status')).toContainText('Unsupported blueprint, model or scenario version');
  await page.getByLabel('Blueprint JSON', { exact: true }).fill(encodeBlueprint(incoming));
  await page.getByRole('button', { name: 'Preview import' }).click();
  await page.getByLabel('Blueprint JSON', { exact: true }).fill('{');
  await expect(page.getByRole('button', { name: 'Confirm replacement' })).toBeDisabled();
  await page.getByRole('button', { name: 'Preview import' }).click();
  await expect(page.getByRole('status')).toContainText('Invalid blueprint JSON');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  mkdirSync('.mini-symphony-evidence', { recursive: true });
  expect(errors).toEqual([]);
  await page.screenshot({ path: `.mini-symphony-evidence/SHE-565-blueprint-after-${mobile ? 'mobile' : 'desktop'}.png`, fullPage: true });
  await page.getByRole('link', { name: 'Recompute policy future' }).click();
  await expect(page.getByRole('heading', { name: 'Month 14', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});
