import { test, expect } from '@playwright/test';
test('mobile keyboard role coordination and private replay', async ({ page }) => {
  await page.goto('/world/storm/');
  await page.getByRole('link', { name: 'Two-player Storm Rescue', exact: true }).click();
  await page.getByRole('button', { name: 'Create private room' }).focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('#keys')).toContainText('Crew key:');
  const text = await page.locator('#keys').textContent();
  const crew = text.match(/Crew key: (.+)/)[1], budget = text.match(/Budget key: (.+)/)[1];
  await page.locator('#key').fill('wrong');
  await page.locator('#refresh').click();
  await expect(page.locator('#status')).toContainText('Access denied');
  await page.locator('#key').fill(crew);
  await page.locator('#refresh').click();
  await page.locator('#crew').click();
  await expect(page.locator('#result')).toContainText('crossing');
  await page.locator('#key').fill(budget);
  await page.locator('#refresh').click();
  await page.locator('#budget').click();
  await expect(page.locator('#result')).toContainText('before');
  await page.locator('#commit').click();
  await expect(page.locator('#status')).toContainText('Committed');
  await page.locator('#replay').click();
  await expect(page.locator('#result')).toContainText('"replay"');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '/private/tmp/SHE-772-mobile.png', fullPage: true });
  await page.locator('#delete').click();
  await expect(page.locator('#status')).toContainText('Room deleted');
});
