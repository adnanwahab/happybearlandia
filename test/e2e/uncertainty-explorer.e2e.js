import {test,expect} from '@playwright/test';
import {resolveCivicExperimentPayload} from '../../world/experiment-contract.js';
test('normal lab entry runs, changes outcome, follows sources, and restores saved distribution',async({page})=>{
 const experiment=resolveCivicExperimentPayload({packages:[{id:'housing',title:'Housing plan',items:[{proposal:{id:'p',title:'Permit more homes'}}]}]},{runs:20,years:2,seed:42}).experiment;
 experiment.worldModel.variables[0].evidence=[{id:'source1',sourceName:'Test research source',url:'https://example.org/research',type:'estimated',geography:'synthetic',notes:'Fixture attribution'}];
 await page.goto('/world/experiment-lab.html');
 await page.locator('#json-input').fill(JSON.stringify(experiment));
 await page.locator('#load-json').click();
 await page.locator('#generate-worlds').click();
 await page.locator('#run-simulations').click();
 const explorer=page.locator('#uncertainty-explorer');
 await expect(explorer).toContainText('20 observed model outputs');
 await expect(explorer).toContainText('20 recorded seeds');
 await expect(explorer).toContainText('Distribution across seeds');
 const select=explorer.getByLabel('Uncertainty outcome');
 const options=await select.locator('option').evaluateAll(nodes=>nodes.map(n=>n.value));
 expect(options.length).toBeGreaterThan(1);
 await select.selectOption(options[1]);
 await expect(explorer).toContainText('Parameter sensitivity ranking');
 await page.locator('#assumptions a').first().click();
 await expect(page).toHaveURL(/#research-assumption-/);
 await expect(page.locator('#research-library a').first()).toHaveAttribute('href','https://example.org/research');
 await expect(page.locator('#validation-output')).toContainText('No empirical validation');
 await page.locator('#save-experiment').click();
 await expect(page.locator('#record-status')).toContainText('Saved record_');
 await page.reload();
 await expect(explorer).toContainText('20 recorded seeds');
 await page.locator('#run-verification').click();
 await expect(page.locator('#verification-output')).toContainText('ALL CHECKS PASSED');
});
