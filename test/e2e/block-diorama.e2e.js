import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
test('keyboard draft, constraints, confirmation and camera restoration without WebGL', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/world/invention/');
  await page.getByRole('link', { name: 'Tabletop Block' }).click();
  await mkdir('.mini-symphony-evidence', { recursive: true });
  await page.screenshot({ path: '.mini-symphony-evidence/SHE-567-local-before.png', fullPage: true });
  const board = page.getByRole('group', { name: 'Synthetic city block' });
  const camera = await board.evaluate(el => getComputedStyle(el).transform);
  await page.getByRole('button', { name: 'Enter tabletop mode' }).click();
  const handle = page.getByRole('button', { name: 'Miniature 1 drag handle' });
  await handle.press('ArrowRight');
  await expect(page.getByLabel('X (meters)')).toHaveValue('-45');
  await page.getByRole('button', { name: 'Rotate 45°' }).click();
  await expect(page.getByRole('status')).toHaveText('No confirmed buildings. Simulation unchanged.');
  await expect(page.locator('#cost')).toContainText('$168,000,000');
  await page.getByLabel('X (meters)').fill('-100');
  await expect(page.getByRole('button', { name: 'Confirm block and run 120 months' })).toBeDisabled();
  await expect(page.locator('#constraints')).toContainText('outside world bounds');
  await page.getByLabel('X (meters)').fill('-45');
  await page.getByRole('button', { name: 'Confirm block and run 120 months' }).click();
  await expect(page.getByRole('status')).toContainText('Confirmed local block');
  await expect(page.locator('#result')).toContainText('modeled public project spending');
  await page.screenshot({ path: '.mini-symphony-evidence/SHE-567-local-after.png', fullPage: true });
  await page.getByLabel('Z (meters)').fill('50');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Enter tabletop mode' })).toBeFocused();
  expect(await board.evaluate(el => getComputedStyle(el).transform)).toBe(camera);
  await page.getByRole('button', { name: 'Enter tabletop mode' }).click();
  await expect(page.getByLabel('Z (meters)')).toHaveValue('0');
});
