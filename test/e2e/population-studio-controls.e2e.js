import {test,expect} from '@playwright/test';

test('studio controls preserve no-op state and synchronize external runtime changes',async({page})=>{
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/world/bench/people');
 await page.evaluate(async()=>{
  document.body.innerHTML='<main id="studio" style="max-width:480px;margin:auto"></main>';
  const {createPopulationRuntime}=await import('/world/population/runtime.js');
  const {mountPopulationStudio}=await import('/world/population/studio.js');
  window.controlRuntime=createPopulationRuntime({config:{population:1000,seed:42}});await controlRuntime.ready;
  window.controlStudio=mountPopulationStudio({container:document.querySelector('#studio'),runtime:controlRuntime,onOpenDashboard:()=>window.dashboardOpened=true});
 });
 const studio=page.getByTestId('population-studio'),search=studio.locator('[data-ps-search]');
 await search.fill('rent policy');
 const rent=studio.locator('[data-population-parameter=rentMultiplier]');
 await rent.fill('1.5');
 await expect(studio.locator('[data-ps-comparison-note]')).toContainText('Actual paired behavior preview');
 await expect(studio.locator('[data-ps-chart] polyline')).toHaveCount(2);
 await expect(rent).toBeVisible();
 await expect(studio.locator('[data-population-parameter=population]')).toBeHidden();
 const before=await page.evaluate(()=>JSON.stringify(controlRuntime.getSnapshot()));
 const chart=await studio.locator('[data-ps-chart]').innerHTML();
 await rent.fill('');await studio.locator('[data-ps-apply]').click();
 await expect(studio.locator('[data-ps-status]')).toContainText('Correct invalid');
 expect(await page.evaluate(()=>JSON.stringify(controlRuntime.getSnapshot()))).toBe(before);
 await rent.fill('1.5');await expect(studio.locator('[data-ps-status]')).toContainText('Settings unchanged');
 expect(await page.evaluate(()=>JSON.stringify(controlRuntime.getSnapshot()))).toBe(before);
 expect(await studio.locator('[data-ps-chart]').innerHTML()).toBe(chart);
 await expect(rent).not.toHaveAttribute('aria-invalid','true');
 await page.evaluate(()=>{controlRuntime.setSpeed(.5);controlRuntime.resume();});
 await expect(studio.locator('[data-ps-speed]')).toHaveValue('0.5');
 await expect(studio.locator('[data-ps-resume]')).toBeDisabled();
 await expect(studio.locator('[data-ps-pause]')).toBeEnabled();
 await page.evaluate(()=>controlRuntime.pause());
 await expect(studio.locator('[data-ps-pause]')).toBeDisabled();
 await page.evaluate(()=>controlRuntime.updateConfig({...controlRuntime.getSnapshot().config,population:1200}));
 await expect(studio.locator('[data-population-parameter=population]')).toHaveValue('1200');
 await expect(studio.locator('[data-population-slider=population]')).toHaveValue('1200');
 await expect(studio.locator('[data-population-parameter=population]')).toBeHidden();
 await expect(rent).toBeVisible();
 await expect(studio.locator('[data-ps-comparison-note]')).toContainText('External settings');
 await expect(studio.locator('[data-ps-comparison-summary]')).toBeEmpty();
 await expect(studio.locator('[data-ps-status]')).toContainText('External settings applied');
 await studio.locator('[data-ps-dashboard]').click();expect(await page.evaluate(()=>window.dashboardOpened)).toBe(true);
 await page.evaluate(()=>controlStudio.focusParameters());await expect(search).toBeFocused();
 await page.screenshot({path:'/private/tmp/hbl-studio-control-audit.png',fullPage:true});
 await page.evaluate(()=>{controlStudio.destroy();controlRuntime.destroy();});
 expect(errors).toEqual([]);
});
