import { test, expect } from '@playwright/test';
test('normal world navigation, editorial failure, success and cancel', async ({ page }) => {
  test.setTimeout(60000);
  await page.goto('/world/?demo=1&synthetic=1&people=16');
  await page.getByRole('link', { name: 'Living Newspaper', exact: true }).click();
  await page.getByRole('button', { name: 'Start editorial challenge' }).click();
  await expect(page.locator('#review-status')).toContainText('No source data');
  await page.getByRole('link', { name: 'Monthly causal demo', exact: true }).click();
  await page.getByRole('button', { name: 'Record deterministic scenario' }).click();
  await expect(page.getByText('Stored month 0 · starting state')).toBeVisible({ timeout: 20000 });
  await page.getByRole('link', { name: 'Living Newspaper', exact: true }).click();
  await page.getByRole('button', { name: 'Start editorial challenge' }).click();
  await expect(page.locator('#editor')).toBeVisible();
  const rows = page.locator('#candidates fieldset');
  for (let i = 0; i < 3; i++) await rows.nth(i).getByRole('checkbox').check();
  await page.getByRole('button', { name: 'Review front page' }).click();
  await expect(page.locator('#review-status')).toContainText('Label the dramatic phrase');
  for (let i = 0; i < 3; i++) await rows.nth(i).locator('[name=label]').selectOption('interpretation');
  await rows.first().locator('[name=treatment]').selectOption('prediction');
  await page.getByRole('button', { name: 'Review front page' }).click();
  await expect(page.locator('#review-status')).toContainText('Unsupported headline');
  await rows.first().locator('[name=treatment]').selectOption('record');
  await page.getByRole('button', { name: 'Review front page' }).click();
  await expect(page.locator('#share-page')).toBeVisible();
  expect(JSON.parse(await page.locator('#share-page').inputValue()).claims).toHaveLength(3);
  await page.getByRole('button', { name: 'Cancel edition' }).click();
  await expect(page.locator('#share-label')).toBeHidden();
  await expect(page.locator('#review-status')).toContainText('cancelled');
});
