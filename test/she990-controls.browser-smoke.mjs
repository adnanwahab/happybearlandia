// Actual canonical World interaction check; requires a running local app and native WebGPU Chrome.
import {chromium,expect} from '@playwright/test';import{writeFile,mkdir}from'node:fs/promises';import{join}from'node:path';
const artifacts=process.env.HBL_BROWSER_ARTIFACT_DIR||'/private/tmp/she990-main-evidence';
 await mkdir(artifacts,{recursive:true});
const browser=await chromium.launch({channel:'chrome',args:['--use-angle=metal','--enable-unsafe-webgpu']});try{const page=await browser.newPage({viewport:{width:1440,height:1000}}),report={controls:[],errors:[],gpuErrors:[]};
 page.on('pageerror',e=>report.errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error'&&/webgpu|GPUValidation|device.?lost/i.test(m.text()))report.gpuErrors.push(m.text());});
 const check=async(name,fn)=>{try{await fn();
 report.controls.push({name,pass:true});}catch(e){report.controls.push({name,pass:false,error:e.message});}};
await page.goto(`${process.env.HBL_BROWSER_BASE_URL || 'http://127.0.0.1:43943'}/world?universeId=universe%3Ahbl%3Amain&worldId=world%3Ahbl%3Amain&scenarioId=scenario%3Ahbl%3Abaseline`);
 await page.waitForFunction(()=>window.hblPersonCommands&&hblWorldStartup?.readyMs,{timeout:90000});
 await page.waitForTimeout(3500);
await check('4× advances model to actual exterior residents',async()=>{await page.locator('[data-launch-speed="4"]').click();
 await page.waitForFunction(()=>hblWorldTileSource.getFrame().people.some(p=>p.mode==='moving'),{},{timeout:20000});
 await page.locator('[data-launch=pause]').click();
 expect(await page.evaluate(()=>hblSimulationPlayback.getState().paused)).toBe(true);});
await page.locator('[data-launch=people]').click();
 report.peoplePanel=await page.locator('#launch-panel').innerText();
 await check('Find someone outside selects actual resident',async()=>{await page.getByRole('button',{name:'Find someone outside',exact:true}).click();
 await expect(page.locator('#inspect')).toBeVisible();
 report.actor=await page.evaluate(()=>hblPersonCommands.getActor());});
await check('Follow and canvas zoom frame resident',async()=>{await page.locator('#followBtn').click();
 await page.mouse.move(800,500);
 await page.waitForFunction(()=>{const s=hblSessionLogState(),a=hblPersonCommands.getActor(),i=hblWorldTileSource.getFrame().people.findIndex(p=>String(p.id)===String(a.id)),m=hblHumanPeople.parts[0].instanceMatrix.array;return Math.hypot(s.target[0]-m[i*16+12],s.target[2]-m[i*16+14])<1;},null,{timeout:30000});
 await page.mouse.wheel(0,-6500);
 await page.waitForTimeout(2500);
 report.visual=await page.evaluate(()=>{const f=hblWorldTileSource.getFrame(),a=hblPersonCommands.getActor(),part=hblHumanPeople.parts[0],arr=part.instanceMatrix.array,visible=[];for(let i=0;i<part.count;i++){const o=i*16;
 if(Math.hypot(arr[o],arr[o+1],arr[o+2])>.001)visible.push({id:f.people[i]?.id,x:arr[o+12],y:arr[o+13],z:arr[o+14],scale:Math.hypot(arr[o],arr[o+1],arr[o+2])});}return{state:hblSessionLogState(),actor:a,renderedCount:visible.length,renderedActor:visible.find(p=>String(p.id)===String(a.id)),rendered:visible.slice(0,12),asset:hblHumanPeople.assetStatus};});
 expect(report.visual.renderedActor).toBeTruthy();
 await page.screenshot({path:join(artifacts,'exterior-follow.png')});});
await page.keyboard.press('Escape');
for(const action of ['quests','legends','search','time'])await check(action+' panel opens/closes',async()=>{await page.locator(`[data-launch=${action}]`).first().click();
 await expect(page.locator('#launch-panel')).toBeVisible();
 await expect(page.locator('#launch-panel [data-launch-content]')).not.toBeEmpty();
 await page.keyboard.press('Escape');
 await expect(page.locator('#launch-panel')).toBeHidden();});
await check('Sound toggles',async()=>{const b=page.locator('[data-launch=sound]');
 await b.click();
 await expect(b).toHaveAttribute('aria-pressed','true');
 await b.click();
 await expect(b).toHaveAttribute('aria-pressed','false');});
await check('Tile view opens/closes',async()=>{await page.locator('[data-launch=tiles]').click();
 await expect(page.getByRole('dialog',{name:'World tile view'})).toBeVisible();
 await page.getByRole('button',{name:'Close tile view',exact:true}).click();});
for(const action of ['world','tools'])await check(action+' exposes advanced tools',async()=>{await page.locator(`[data-launch=${action}]`).click();
 await expect(page.locator('#top')).toBeVisible();
 await expect(page.locator('#top')).toHaveAttribute('open','');
 await page.keyboard.press('Escape');});
await check('Laws opens choice dialog',async()=>{await page.locator('[data-launch=laws]').click();
 await expect(page.getByRole('dialog',{name:'Choose a law',exact:true})).toBeVisible();
 await page.keyboard.press('Escape');});
await check('Build opens tools',async()=>{await page.locator('[data-launch=build]').click();
 await expect(page.locator('.bw-world-tools')).toHaveAttribute('open','');
 await page.keyboard.press('Escape');});
await check('Activity history opens/closes',async()=>{await page.locator('[data-launch=activity]').click();
 const d=page.getByRole('dialog',{name:'Activity history dashboard'});
 await expect(d).toBeVisible();
 await d.getByRole('button',{name:'Close',exact:true}).click();});
await check('Overlay changes actual selector',async()=>{const before=await page.locator('#overlayMode').inputValue();
 await page.locator('[data-launch=overlay]').click();
 expect(await page.locator('#overlayMode').inputValue()).not.toBe(before);});
for(const speed of [1,2,4])await check('speed '+speed,async()=>{await page.locator(`[data-launch-speed="${speed}"]`).click();
 expect(await page.evaluate(()=>hblSimulationPlayback.getState().speed)).toBe(speed);});
 await page.locator('[data-launch=pause]').click();
await page.setViewportSize({width:390,height:844});
 await page.reload();
 await page.waitForFunction(()=>window.hblPersonCommands&&hblWorldStartup?.readyMs,{timeout:90000});
 await check('mobile People panel fits viewport',async()=>{await page.locator('[data-launch=people]').click();
 const b=await page.locator('#launch-panel').boundingBox();
 expect(b.x).toBeGreaterThanOrEqual(0);
 expect(b.x+b.width).toBeLessThanOrEqual(390);
 await page.screenshot({path:join(artifacts,'mobile-people.png')});
 await page.keyboard.press('Escape');});
 report.mobileControls=await page.locator('[data-launch]').evaluateAll(bs=>bs.map(b=>({action:b.dataset.launch,visible:!!b.getClientRects().length})));
 await writeFile(join(artifacts,'controls.json'),JSON.stringify(report,null,2));
 console.log(JSON.stringify(report.controls));
 if(report.controls.some(row=>!row.pass)||report.errors.length||report.gpuErrors.length)process.exitCode=1;
}finally{await browser.close();}
