import { test, expect } from '@playwright/test';
test('explicit review, real endpoint persistence, retries, export, deletion and failure',async({page},info)=>{
 const external=[];page.on('request',r=>{if(!r.url().startsWith('http://127.0.0.1:'))external.push(r.url());});
 await page.goto('/');
 const status=page.getByRole('status');
 await expect(page.getByRole('button',{name:'Store pilot locally',exact:true})).toBeDisabled();
 await page.getByLabel('Pilot brief').fill('<b>Local housing pilot</b>');
 await page.getByRole('button',{name:'Review pilot brief'}).click();
 await expect(page.locator('[data-preview]')).toContainText('<b>Local housing pilot</b>');
 await expect(page.locator('[data-preview] b')).toHaveCount(0);
 await page.getByLabel('I consent to local storage').check();
 await page.getByLabel('I reviewed this exact brief').check();
 await page.getByRole('button',{name:'Store pilot locally',exact:true}).click();
 await expect(status).toContainText('Stored locally; not submitted externally');
 await page.getByRole('button',{name:'Store pilot locally',exact:true}).click();
 await expect(status).toContainText('Stored locally; not submitted externally');
 await page.getByRole('button',{name:'Export my local records'}).click();
 await expect(status).toContainText('product-workflow-export.v1');
 expect(JSON.parse(await status.innerText()).records).toHaveLength(1);
 await page.getByLabel('I reviewed the selected event').check();
 await page.getByRole('button',{name:'Store selected event locally'}).click();
 await expect(status).toContainText('Stored locally');
 await expect(page.getByLabel('I consent to local storage')).toBeChecked();
 await page.getByLabel('I consent to local storage').uncheck();
 await expect(page.getByRole('button',{name:'Store selected event locally'})).toBeDisabled();
 await page.getByLabel('I consent to local storage').check();
 await expect(page.getByRole('button',{name:'Store selected event locally'})).toBeDisabled();
 await page.screenshot({path:info.outputPath('consented-local-receipt.png'),fullPage:true});
 await page.reload(); await expect(page.getByLabel('I consent to local storage')).not.toBeChecked();
 await page.getByRole('button',{name:'Export my local records'}).click();
 await expect(status).toContainText('studio_opened');expect(JSON.parse(await status.innerText()).records).toHaveLength(2);
 await page.getByRole('button',{name:'Delete my local records'}).click();await expect(status).toContainText('Deleted 2');
 await page.getByRole('button',{name:'Export my local records'}).click();await expect(status).toContainText('"records": []');
 await page.getByLabel('Pilot brief').fill('Retained draft');await page.getByRole('button',{name:'Review pilot brief'}).click();
 await page.getByLabel('I consent to local storage').check();await page.getByLabel('I reviewed this exact brief').check();
 await page.route('**/api/product-workflows',route=>route.fulfill({status:503,contentType:'application/json',body:'{"error":"Local workflow storage unavailable"}'}));
 await page.getByRole('button',{name:'Store pilot locally',exact:true}).click();await expect(status).toContainText('Local storage failed');
 await expect(page.getByLabel('Pilot brief')).toHaveValue('Retained draft');
 await page.screenshot({path:info.outputPath('storage-error-retained-draft.png'),fullPage:true});
 expect(external).toEqual([]);
});
test('real endpoint rejects malformed, foreign origin, unsupported methods and oversized body',async({request})=>{
 const headers={'x-local-review':'1','content-type':'application/json'};
 expect((await request.post('/api/product-workflows',{headers:{...headers,origin:'https://foreign.invalid'},data:'{}'})).status()).toBe(401);
 expect((await request.post('/api/product-workflows',{headers,data:'{'})).status()).toBe(400);
 expect((await request.patch('/api/product-workflows',{headers})).status()).toBe(405);
 expect((await request.post('/api/product-workflows',{headers,data:'x'.repeat(17000)})).status()).toBe(413);
 expect((await request.post('/api/product-workflows',{headers:{'x-local-review':'1','content-type':'text/plain'},data:'{}'})).status()).toBe(415);
});
